// Downloads Google Sans (SIL Open Font License, via Google Fonts) for the
// latin, latin-ext, cyrillic, cyrillic-ext and armenian subsets and writes a
// self-hosted @font-face stylesheet. Run once: `node scripts/fetch-google-sans.mjs`
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const KEEP = ['armenian', 'cyrillic-ext', 'cyrillic', 'latin-ext', 'latin'];
const outDir = path.join(process.cwd(), 'public', 'fonts', 'google-sans');
const css = await (await fetch('https://fonts.googleapis.com/css2?family=Google+Sans:ital,wght@0,400..700;1,400..700&display=swap', { headers: { 'User-Agent': UA } })).text();

await mkdir(outDir, { recursive: true });
const blocks = css.split('/* ').slice(1);
let out = '/* Google Sans — SIL Open Font License 1.1. Generated by scripts/fetch-google-sans.mjs */\n';
for (const block of blocks) {
  const subset = block.slice(0, block.indexOf(' */'));
  if (!KEEP.includes(subset)) continue;
  const style = block.match(/font-style: (\w+)/)[1];
  const url = block.match(/url\((.+?)\)/)[1];
  const range = block.match(/unicode-range: (.+?);/)[1];
  const file = `google-sans-${subset}-${style}.woff2`;
  await writeFile(path.join(outDir, file), Buffer.from(await (await fetch(url)).arrayBuffer()));
  out += `@font-face{font-family:'Google Sans';font-style:${style};font-weight:400 700;font-display:swap;src:url(/fonts/google-sans/${file}) format('woff2');unicode-range:${range};}\n`;
}
await writeFile(path.join(process.cwd(), 'src', 'app', 'google-sans.css'), out);
console.log('done');
